function writeAdapterPointers(projectRoot, detection, requestedAdapter) {
  if (requestedAdapter === 'none') return [];

  const adapters = new Set();

  for (const config of detection.agentConfigs) {
    if (config.includes('CLAUDE.md')) adapters.add('claude');
    if (config.includes('.cursorrules')) adapters.add('cursor');
    if (config.includes('AGENTS.md')) adapters.add('generic');
  }

  if (requestedAdapter && requestedAdapter !== 'none') {
    adapters.add(requestedAdapter);
  }

  const written = [];
  for (const adapter of adapters) {
    const pointer = ADAPTER_POINTERS[adapter];
    const filePath = path.join(projectRoot, pointer.file);
    writeManagedPointer(filePath, pointer.body);
    written.push(pointer.file);
  }

  return written;
}

function validateRequestedAdapter(requestedAdapter) {
  if (requestedAdapter && requestedAdapter !== 'none' && !ADAPTER_POINTERS[requestedAdapter]) {
    throw new Error(`Unknown adapter: ${requestedAdapter}. Use claude, cursor, codex, generic, or none.`);
  }
}

function writeManagedPointer(filePath, pointerBody) {
  const markerStart = '<!-- agentbubble:start -->';
  const markerEnd = '<!-- agentbubble:end -->';
  const block = `${markerStart}\n${pointerBody.trim()}\n${markerEnd}\n`;

  if (!fs.existsSync(filePath)) {
    writeText(filePath, `${pointerBody.trim()}\n`);
    return;
  }

  const existing = fs.readFileSync(filePath, 'utf8');
  const expression = new RegExp(`${escapeRegExp(markerStart)}[\\s\\S]*?${escapeRegExp(markerEnd)}\\n?`, 'm');
  if (expression.test(existing)) {
    writeText(filePath, existing.replace(expression, block));
  } else {
    const separator = existing.trim().length > 0 ? '\n\n' : '';
    writeText(filePath, `${existing.replace(/\s*$/, '')}${separator}${block}`);
  }
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function renderSummary({ writtenFiles, detection, adapters }) {
  const unknowns = [
    detection.productGoal === UNKNOWN ? 'product goal' : undefined,
    detection.framework === UNKNOWN ? 'framework' : undefined,
    detection.packageManager === UNKNOWN ? 'package manager' : undefined,
    detection.testCommand === UNKNOWN ? 'test command' : undefined,
    detection.buildCommand === UNKNOWN ? 'build command' : undefined,
    detection.authTooling === UNKNOWN ? 'auth tooling' : undefined,
    detection.databaseTooling === UNKNOWN ? 'database tooling' : undefined
  ].filter(Boolean);

  return `AgentBubble initialized.

Files created:
${writtenFiles.map((file) => `- ${file}`).join('\n')}

Detected stack/tooling:
- Framework: ${detection.framework}
- Package manager: ${detection.packageManager}
- Test command: ${detection.testCommand}
- Build command: ${detection.buildCommand}
- App structure: ${detection.appStructure}
- Database/auth: ${detection.databaseTooling} / ${detection.authTooling}
- CI: ${detection.ciTooling}
- Existing agent config: ${detection.agentConfigs.length > 0 ? detection.agentConfigs.join(', ') : UNKNOWN}

Unknowns remaining:
${unknowns.length > 0 ? unknowns.map((unknown) => `- ${unknown}`).join('\n') : '- none from MVP detection fields'}

Adapter pointers written:
${adapters.length > 0 ? adapters.map((adapter) => `- ${adapter}`).join('\n') : '- none'}

Next command/prompt:
- Ask your agent to read .agentbubble/session-start.md
`;
}
