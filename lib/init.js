import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import readline from 'node:readline/promises';

import { ADAPTER_POINTERS, REQUIRED_AGENTBUBBLE_FILES, UNKNOWN } from './constants.js';
import { detectProject } from './detect.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(__dirname, '..');
const templateRoot = path.join(packageRoot, 'templates', 'base', '.agentbubble');

export async function initAgentBubble(options = {}) {
  const projectRoot = path.resolve(options.projectRoot || process.cwd());
  const destination = path.join(projectRoot, '.agentbubble');

  if (fs.existsSync(destination) && !options.force) {
    const error = new Error('.agentbubble/ already exists. AgentBubble did not overwrite it. Rerun with `agentbubble init --force` only after reviewing the existing folder.');
    error.exitCode = 1;
    throw error;
  }

  validateTemplate();
  validateRequestedAdapter(options.adapter);

  const detection = detectProject(projectRoot);
  const answers = options.nonInteractive ? {} : await askCriticalQuestions();

  if (fs.existsSync(destination) && options.force) {
    fs.rmSync(destination, { recursive: true, force: true });
  }

  copyDirectory(templateRoot, destination);

  const writtenFiles = REQUIRED_AGENTBUBBLE_FILES.map((file) => path.join('.agentbubble', file));
  writeText(path.join(destination, 'context.md'), renderContext(detection, answers));
  writeText(path.join(destination, 'architecture.md'), renderArchitecture(detection, answers));

  const adapters = writeAdapterPointers(projectRoot, detection, options.adapter);

  return {
    detection,
    filesCreated: writtenFiles,
    adapters,
    summary: renderSummary({ writtenFiles, detection, adapters })
  };
}

function validateTemplate() {
  if (!fs.existsSync(templateRoot)) {
    throw new Error(`Missing base template: ${templateRoot}`);
  }

  const missing = REQUIRED_AGENTBUBBLE_FILES.filter((file) => !fs.existsSync(path.join(templateRoot, file)));
  if (missing.length > 0) {
    throw new Error(`Base template is missing required files: ${missing.join(', ')}`);
  }
}

async function askCriticalQuestions() {
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
  });

  try {
    const productGoal = await rl.question('Product goal (press Enter for unknown): ');
    const doNotTouch = await rl.question('Dangerous areas agents should not touch without approval (press Enter for unknown): ');
    const qaCommand = await rl.question('QA-ready command/check (press Enter for unknown): ');
    return {
      productGoal: productGoal.trim() || undefined,
      doNotTouch: doNotTouch.trim() || undefined,
      qaCommand: qaCommand.trim() || undefined
    };
  } finally {
    rl.close();
  }
}

function copyDirectory(source, destination) {
  fs.mkdirSync(destination, { recursive: true });
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    const sourcePath = path.join(source, entry.name);
    const destinationPath = path.join(destination, entry.name);
    if (entry.isDirectory()) {
      copyDirectory(sourcePath, destinationPath);
    } else if (entry.isFile()) {
      fs.copyFileSync(sourcePath, destinationPath);
    }
  }
}

function writeText(filePath, content) {
  fs.writeFileSync(filePath, content, 'utf8');
}

